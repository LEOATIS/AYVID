"""Supervisor LangGraph node — Bayesian Update Operator.

Runs AFTER the auditor has approved a trade and BEFORE the execute
edge. Its job is not to re-decide direction; it is to select the
`strategy_parameters` the downstream execution engine should use,
grounded in the empirical priors generated by
`backtesting.calibrate`.

Decision flow inside the node
──────────────────────────────
1. **Short-circuit** if the auditor already rejected (`HOLD`).
2. **Compute the live RegimeState** for the target ticker and
   translate it into the priors-file bucket key (e.g.
   ``STRONG_TREND_DOWN__CRISIS``).
3. **Infer the candidate strategy name** from the mapper/auditor
   rationale (canonical names are stamped as ``[name]`` at the head
   of the string by the rule-based orchestrator; the free-text
   LLM-driven path is classified heuristically).
4. **Look up the prior** in ``calibration/priors.json``. If the cell
   is flagged ``blocked_by_regime``, HARD-SKIP the trade — the
   historical backtest proved this combination unprofitable and no
   amount of LLM sophistry should override that ground truth.
5. **Call the Supervisor LLM** with the priors block injected into
   the prompt. The call uses LangChain's ``with_structured_output``
   against the `SupervisorDecision` Pydantic model so hallucinated
   / out-of-bounds parameters are rejected at the SDK boundary.
6. **Update state** with the `strategy_parameters` dict. Downstream,
   ``strategy_orchestrator.get_param()`` reads this first (Tier-1);
   anything omitted falls through to the prior (Tier-2) and then
   the hardcoded default (Tier-3).

The node is intentionally defensive: any failure (network, LLM
schema mismatch, missing priors file) degrades gracefully to an
empty parameters dict, which simply triggers the Tier-2/3 fallbacks
in the orchestrator. We never let a broken LLM kill the pipeline.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

import numpy as np
from langchain_core.messages import HumanMessage, SystemMessage
from pydantic import ValidationError

from graph_intelligence.agents.strategist.schema import (
    CANONICAL_STRATEGIES,
    SupervisorDecision,
)
from graph_intelligence.agents.supervisor.prompts import (
    SUPERVISOR_SYSTEM,
    SUPERVISOR_USER_TEMPLATE,
    render_priors_block,
)
from graph_intelligence.graph_state.state import CausalArbitrageState
from shared.logger import get_logger

log = get_logger("agent.supervisor")

_PRIORS_PATH: Path = Path("calibration/priors.json")

# Strategy-name inference — the rule-based orchestrator stamps the
# canonical name as ``[strategy_name] ...`` at the start of every
# rationale. We parse that first, then fall back to keyword matching
# for LLM-driven paths where the convention may not be followed.
_STRATEGY_BRACKET_RE = re.compile(r"^\s*\[([a-z0-9_]+)\]", re.IGNORECASE)

_STRATEGY_KEYWORD_MAP: list[tuple[str, str]] = [
    ("supply chain benef", "supply_chain_beneficiary"),
    ("supply chain capitu", "supply_chain_oversold_dip"),
    ("supply chain overso", "supply_chain_oversold_dip"),
    ("deep value", "deep_value_investment"),
    ("trend invest", "trend_investment"),
    ("mr bounce", "mr_equity_bounce"),
    ("shock-directed put", "shock_directed_put"),
    ("shock-directed call", "shock_directed_call"),
    ("crisis put", "crisis_index_put"),
    ("crisis capitulation", "crisis_capitulation_bounce"),
    ("bull call spread", "idx_bull_spread"),
    ("bear put spread", "idx_bear_spread"),
    # Multi-asset strategies
    ("fx macro", "fx_macro_trend"),
    ("fx carry", "fx_carry_trade"),
    ("fx mean rev", "fx_mean_reversion"),
    ("commodity supply", "commodity_supply_shock"),
    ("commodity momentum", "commodity_momentum"),
    ("commodity season", "commodity_seasonal"),
    ("crypto momentum", "crypto_momentum"),
    ("crypto supply", "crypto_supply_chain"),
    ("rates macro", "rates_macro"),
    ("rates steep", "rates_steepener_flattener"),
    ("rates flatten", "rates_steepener_flattener"),
    ("sector rotation", "sector_rotation_etf"),
    ("factor etf", "factor_etf_momentum"),
    ("etf supply chain", "etf_supply_chain_expression"),
]


# ── Priors loader (mtime-cached) ──────────────────────────────────────
_priors_cache: dict[str, Any] | None = None
_priors_mtime: float | None = None


def _load_priors() -> dict[str, Any]:
    """Read + cache `calibration/priors.json`.

    Returns the inner `priors` subtree (strategy → regime → cell).
    Empty dict when the file is missing — the node then skips the
    priors block gracefully and lets the LLM operate on defaults.
    """
    global _priors_cache, _priors_mtime
    try:
        mtime = _PRIORS_PATH.stat().st_mtime
    except OSError:
        _priors_cache = {}
        _priors_mtime = None
        return _priors_cache

    if _priors_cache is not None and _priors_mtime == mtime:
        return _priors_cache

    try:
        payload = json.loads(_PRIORS_PATH.read_text())
        _priors_cache = payload.get("priors", {}) if isinstance(payload, dict) else {}
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        log.warning(f"priors.json load failed: {exc}; falling back to empty")
        _priors_cache = {}
    _priors_mtime = mtime
    return _priors_cache


# ── Regime computation for the target ticker ─────────────────────────
async def _compute_regime_for_target(target_ticker: str) -> tuple[str, str]:
    """Compute the regime block + priors-bucket key for a ticker.

    Returns ``(regime_block_text, regime_key)``. Falls back to a
    neutral block string + ``CHOPPY__NORMAL`` when OHLCV is
    unavailable — the Supervisor then just can't pull priors for
    this trade.
    """
    try:
        from data_primitives.extractors.openbb_client import fetch_ohlcv
        from shared.quant.regime import classify_regime
        from shared.quant.signals import compute_hurst_exponent

        bars = await fetch_ohlcv(target_ticker, days=90)
        if not bars or len(bars) < 30:
            return ("(regime unavailable — insufficient OHLCV)", "CHOPPY__NORMAL")

        closes = np.array([b.close for b in bars])
        highs = np.array([b.high for b in bars])
        lows = np.array([b.low for b in bars])
        volumes = np.array([b.volume for b in bars], dtype=float)

        log_rets = np.diff(np.log(closes))
        hurst = compute_hurst_exponent(log_rets)
        iv_proxy = (
            float(np.std(log_rets[-20:], ddof=1) * np.sqrt(252))
            + abs(float(closes[-1] / closes[-6] - 1)) * 2.0
            + 0.02
        )
        rs = classify_regime(
            closes,
            highs,
            lows,
            volumes,
            hurst=hurst,
            implied_vol=iv_proxy,
        )
        ret_20d = float(closes[-1] / closes[-21] - 1) if len(closes) >= 21 else 0.0

        direction = ""
        trend = rs.trend_regime.value
        if trend in ("STRONG_TREND", "WEAK_TREND"):
            direction = "_UP" if ret_20d >= 0 else "_DOWN"
        regime_key = f"{trend}{direction}__{rs.volatility_regime.value}"

        regime_block = (
            f"volatility_regime: {rs.volatility_regime.value}\n"
            f"trend_regime: {trend}\n"
            f"composite_regime: {rs.composite_regime.value}\n"
            f"adx: {rs.adx_value:.1f}\n"
            f"hurst: {hurst:.3f}\n"
            f"realized_vol: {rs.realized_vol_annualized:.1%}\n"
            f"vol_percentile: {rs.vol_percentile:.0f}\n"
            f"vrp: {rs.vrp:+.3f}\n"
            f"grind_up_flag: {rs.grind_up_flag}\n"
            f"ret_20d: {ret_20d:+.2%}\n"
            f"-> regime_key: {regime_key}"
        )
        return regime_block, regime_key
    except Exception as exc:
        log.debug(f"Supervisor regime compute failed for {target_ticker}: {exc}")
        return ("(regime unavailable)", "CHOPPY__NORMAL")


# ── Strategy-name inference ──────────────────────────────────────────
def _infer_strategy_name(state: CausalArbitrageState) -> str:
    """Best-effort extraction of the canonical strategy name.

    Returns ``""`` when we can't classify — in that case the priors
    lookup falls back to defaults silently.
    """
    rationale = (state.get("rationale") or "").strip()

    m = _STRATEGY_BRACKET_RE.match(rationale)
    if m:
        candidate = m.group(1).lower()
        if candidate in CANONICAL_STRATEGIES:
            return candidate

    haystack = rationale.lower()
    for kw, canonical in _STRATEGY_KEYWORD_MAP:
        if kw in haystack:
            return canonical

    preferred = state.get("preferred_strategies") or []
    if preferred:
        # Strategist's preferred list — pick the first whose bias
        # matches the proposed action.
        action = (state.get("proposed_action") or "").upper()
        if action == "LONG":
            long_biased = (
                "supply_chain_beneficiary",
                "deep_value_investment",
                "trend_investment",
                "mr_equity_bounce",
                "idx_bull_spread",
                "idx_momentum",
            )
            for s in preferred:
                if s in long_biased:
                    return s
        return preferred[0]

    return ""


# ── LLM wiring (structured output) ───────────────────────────────────
def _get_structured_llm():
    """Build a `SupervisorDecision`-shaped LLM client.

    LangChain's ``with_structured_output`` forces the LLM to emit a
    payload that Pydantic can validate — hallucinations outside the
    schema raise at the SDK boundary and are caught below.
    """
    from shared.llm_client import get_langchain_chat_model

    return get_langchain_chat_model(
        temperature=0.05,
        max_tokens=1500,
    ).with_structured_output(SupervisorDecision)


# ── Prompt rendering helpers ─────────────────────────────────────────
def _render_live_signals_block(state: CausalArbitrageState) -> str:
    """Condensed live quantitative signals pulled from `quant_data`."""
    quant = state.get("quant_data") or ""
    if not quant:
        return "(no live signals available)"
    lines = [ln.rstrip() for ln in quant.splitlines() if ln.strip()]
    return "\n".join(lines[-25:])


def _render_shock_context_block(state: CausalArbitrageState) -> str:
    intel = state.get("causal_intel") or {}
    if not intel:
        return "(no causal shock context provided)"
    return json.dumps(intel, indent=2, default=str)[:800]


def _render_cost_hurdle_block(state: CausalArbitrageState) -> str:
    """Simple placeholder for the cost hurdle block.

    The orchestrator already enforces the 4× cost hurdle numerically
    (`_orchestrator_ev_gate`). We remind the LLM of the policy so its
    parameter choices respect it.
    """
    return (
        "Policy: every parameter you pick must leave "
        "expected_return >= 4 × modeled round-trip cost. "
        "The execution engine enforces this check independently — "
        "trades that fail the EV hurdle are killed automatically. "
        "If your proposed parameters cannot clear 4× cost under "
        "current spreads, set approved=false."
    )


# ── Node entrypoint ──────────────────────────────────────────────────
async def supervisor_node(state: CausalArbitrageState) -> dict:
    """Supervisor LangGraph node — emits `strategy_parameters`.

    Return-value contract (to be merged into the LangGraph state):
      - ``strategy_parameters: dict``  — authoritative params for
        this trade. Empty dict when the Supervisor has no opinion
        (LLM down, schema invalid, etc.); callers fall back to the
        prior / default tiers in the orchestrator.
      - ``proposed_action: "HOLD"``    — on explicit rejection only.
      - ``confidence: float``          — may be bumped by the LLM.
      - ``supervisor_rationale: str``  — diagnostic for the auditor.
    """
    target = state.get("target_ticker") or ""
    action = (state.get("proposed_action") or "").upper()

    # Short-circuit: nothing to parameterise.
    if not target:
        log.debug("Supervisor skipped — no target ticker in state")
        return {"strategy_parameters": {}}
    if action in ("", "HOLD"):
        log.debug("Supervisor skipped — auditor already HOLD")
        return {"strategy_parameters": {}}

    # 1. Regime for the target
    regime_block, regime_key = await _compute_regime_for_target(target)

    # 2. Candidate strategy name
    strategy_name = _infer_strategy_name(state)
    if not strategy_name:
        log.info(
            f"Supervisor: could not classify strategy for {target}; deferring to Tier-3 defaults"
        )
        return {"strategy_parameters": {}}

    # 3. Priors
    priors = _load_priors()
    cell = priors.get(strategy_name, {}).get(regime_key, {})
    priors_text = render_priors_block(strategy_name, regime_key, priors)

    # 4. Hard-block on empirically-proven-unprofitable cells.
    if cell.get("blocked_by_regime"):
        log.warning(
            f"[SUPERVISOR-BLOCK] {strategy_name} × {regime_key}: "
            f"priors mark this cell as blocked (best_sharpe_seen="
            f"{cell.get('best_sharpe_seen', 0):+.2f}, n={cell.get('n', 0)}). "
            f"Rejecting trade."
        )
        return {
            "strategy_parameters": {},
            "proposed_action": "HOLD",
            "confidence": 0.0,
            "supervisor_rationale": (
                f"priors.json marks {strategy_name} × {regime_key} as "
                f"historically unprofitable (best Sharpe "
                f"{cell.get('best_sharpe_seen', 0):+.2f})."
            ),
        }

    # 5. LLM call with structured output.
    prompt = SUPERVISOR_USER_TEMPLATE.format(
        ticker=target,
        strategy_name=strategy_name,
        regime_key=regime_key,
        regime_block=regime_block,
        empirical_priors_block=priors_text,
        live_signals_block=_render_live_signals_block(state),
        shock_context_block=_render_shock_context_block(state),
        cost_hurdle_block=_render_cost_hurdle_block(state),
    )

    try:
        llm = _get_structured_llm()
        decision: SupervisorDecision = await llm.ainvoke(
            [
                SystemMessage(content=SUPERVISOR_SYSTEM),
                HumanMessage(content=prompt),
            ]
        )
    except (ValidationError, ValueError, TypeError) as exc:
        log.warning(
            f"[SUPERVISOR] LLM output failed validation: {exc}; "
            f"degrading to Tier-2/3 fallbacks (empty params dict)"
        )
        return {"strategy_parameters": {}}
    except Exception as exc:
        log.warning(f"[SUPERVISOR] LLM invocation failed: {exc}; degrading to Tier-2/3 fallbacks")
        return {"strategy_parameters": {}}

    # 6. Post-validation — enforce schema invariants defensively.
    # `with_structured_output` already validated the Pydantic types
    # but the LLM could still return a non-canonical strategy_name
    # or flip approved=True with zero conviction.
    if not isinstance(decision, SupervisorDecision):
        log.warning("[SUPERVISOR] Non-SupervisorDecision return; empty params")
        return {"strategy_parameters": {}}

    if decision.strategy_name and decision.strategy_name not in CANONICAL_STRATEGIES:
        log.warning(
            f"[SUPERVISOR] LLM emitted non-canonical strategy '{decision.strategy_name}'; ignoring"
        )
        decision.strategy_name = strategy_name  # snap back to inferred

    # 7. Explicit rejection path.
    if not decision.approved:
        reason = ", ".join(decision.kill_reasons) if decision.kill_reasons else decision.rationale
        log.info(f"[SUPERVISOR] rejected trade for {target}: {reason}")
        return {
            "strategy_parameters": {},
            "proposed_action": "HOLD",
            "confidence": 0.0,
            "supervisor_rationale": f"Supervisor rejected: {reason or 'no rationale'}",
        }

    # 8. Approved — extract params and merge into state.
    #    `exclude_defaults=True` would drop any parameter the LLM
    #    did not explicitly override, so the Tier-2 prior lookup
    #    inside the orchestrator still runs for those fields.
    try:
        params = decision.strategy_parameters.model_dump(exclude_defaults=True)
    except Exception:
        params = decision.strategy_parameters.model_dump()

    log.info(
        f"[SUPERVISOR] APPROVED {decision.strategy_name} × {regime_key} "
        f"conv={decision.conviction:.2f} R={decision.expected_r:.1f} "
        f"params={params}"
    )

    # P1-K: conservative merge — both layers must agree for high
    # conviction. The previous implementation used max(), which
    # could only ratchet conviction UP: a hallucinated
    # `decision.conviction = 0.99` would silently override a
    # pipeline-side 0.4. Under min() the pipeline's consensus
    # (analyst swarm + debate) still floors the outcome, so an
    # over-confident supervisor cannot promote a weak upstream
    # signal past ``SUPERVISOR_MIN_CONFIDENCE``.
    pipeline_conf = float(state.get("confidence") or 0.0)
    supervisor_conf = float(decision.conviction or 0.0)
    merged_confidence = min(pipeline_conf, supervisor_conf)

    if pipeline_conf > supervisor_conf:
        log.info(
            f"[SUPERVISOR] conviction floor: pipeline={pipeline_conf:.2f}, "
            f"supervisor={supervisor_conf:.2f} → keeping supervisor "
            f"(post-priors view is more conservative)"
        )

    return {
        "strategy_parameters": params,
        "confidence": merged_confidence,
        "supervisor_rationale": decision.rationale or "",
        "proposed_action": action,  # unchanged — we don't override direction
    }


